import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { createModelPreset, exportModelProfiles } from '../../src/react-app/providers/model-profiles';
import { clickAppAction, createVault, toneWav } from './helpers';

test('policy rejection offers explicit review and a new consented request without automatic relaxation', async ({ page, baseURL }) => {
  const evidence = process.env.MOM_RELEASE_EVIDENCE ?? '/private/tmp/mom-stt-policy-recovery';
  mkdirSync(evidence, { recursive: true });
  const calls: Record<string, unknown>[] = [], external: string[] = [], errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', async route => {
    const request = route.request();
    if (new URL(request.url()).origin === new URL(baseURL!).origin) return route.continue();
    if (request.url() !== 'https://openrouter.ai/api/v1/audio/transcriptions') { external.push(request.url()); return route.abort(); }
    const headers = { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': '*', 'Access-Control-Allow-Methods': 'POST, OPTIONS' };
    if (request.method() === 'OPTIONS') return route.fulfill({ status: 204, headers });
    calls.push(request.postDataJSON());
    return route.fulfill({ status: calls.length === 1 ? 404 : 200, headers, contentType: 'application/json', body: JSON.stringify(calls.length === 1 ? { error: { code: 404, message: 'PRIVATE_UPSTREAM_POLICY_TEXT', metadata: { failed_routing_step: 'Filter by Data Policy' } } } : { text: 'SYNTHETIC_POLICY_REVIEW_TRANSCRIPT' }) });
  });
  await createVault(page); await clickAppAction(page, '설정');
  const keys = page.getByRole('region', { name: 'API 키 관리', exact: true });
  await keys.getByRole('button', { name: 'API 키 추가', exact: true }).click();
  let editor = page.getByRole('dialog', { name: 'API 키 추가', exact: true });
  await editor.getByLabel('키 이름', { exact: true }).fill('SYNTHETIC_ROUTER');
  await editor.getByRole('combobox', { name: '제공사', exact: true }).selectOption('openrouter');
  await editor.getByLabel('새 API 키', { exact: true }).fill('SYNTHETIC_POLICY_TEST_KEY');
  await editor.getByRole('checkbox', { name: '선택한 OpenRouter 전송·보관 정책을 확인했어요', exact: true }).check();
  await editor.getByRole('button', { name: '키 저장', exact: true }).click(); await expect(editor).toHaveCount(0);
  const manager = page.getByRole('region', { name: '모델 관리', exact: true });
  await manager.getByRole('button', { name: 'JSON 가져오기', exact: true }).click();
  const model = { ...createModelPreset('router-qwen3-asr-1.7b'), name: 'SYNTHETIC_POLICY_MODEL' };
  const importer = page.getByRole('region', { name: '모델 가져오기', exact: true });
  await importer.getByLabel('모델 JSON', { exact: true }).fill(exportModelProfiles([model]));
  await importer.getByRole('button', { name: '미리보기', exact: true }).click(); await importer.getByRole('button', { name: '가져오기', exact: true }).click();
  await manager.getByRole('listitem').filter({ has: page.getByText(model.name, { exact: true }) }).getByRole('button', { name: '수정', exact: true }).click();
  editor = page.getByRole('dialog', { name: '모델 수정', exact: true });
  await editor.getByRole('combobox', { name: 'API 키 선택', exact: true }).selectOption({ label: 'SYNTHETIC_ROUTER' });
  await editor.getByRole('checkbox', { name: '이 모델 활성화', exact: true }).check();
  await editor.getByRole('button', { name: '저장', exact: true }).click(); await expect(editor).toHaveCount(0);
  await page.getByRole('button', { name: 'Minutes of Meeting', exact: true }).click();
  await page.getByRole('main').getByRole('button', { name: '+ 새 음성 메모', exact: true }).click();
  await page.getByLabel('음성 파일 선택', { exact: true }).setInputFiles({ name: 'SYNTHETIC_POLICY.wav', mimeType: 'audio/wav', buffer: toneWav(4) });
  await page.getByRole('button', { name: '전사 준비', exact: true }).click();
  await page.getByRole('button', { name: '전사하기 →', exact: true }).click();
  await page.getByRole('combobox', { name: '전사 모델', exact: true }).selectOption({ label: model.name });
  await page.getByRole('checkbox', { name: '위 내용을 확인했어요', exact: true }).check();
  await page.getByRole('button', { name: '전사 실행', exact: true }).click();
  const recovery = page.getByRole('region', { name: '보관 정책으로 전사 차단', exact: true });
  await expect(recovery).toBeVisible(); expect(calls).toHaveLength(1);
  expect(calls[0].provider).toMatchObject({ data_collection: 'deny', zdr: true });
  await expect(page.getByRole('button', { name: '전체 전사', exact: true })).toBeDisabled();
  await expect(page.locator('body')).not.toContainText('PRIVATE_UPSTREAM_POLICY_TEXT');
  await page.screenshot({ path: `${evidence}/1440-policy-blocked.png`, fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  await recovery.getByRole('button', { name: '보관 정책 검토', exact: true }).click();
  editor = page.getByRole('dialog', { name: 'API 키 수정', exact: true });
  await expect(editor).toContainText('모든 모델에 적용');
  await expect(editor).toContainText('계정·가드레일에서 강제한 ZDR');
  await expect(editor.getByLabel('새 API 키', { exact: true })).toHaveValue('');
  expect(await editor.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
  await page.screenshot({ path: `${evidence}/360-policy-review.png` });
  await editor.getByRole('link', { name: 'OpenRouter 계정 보관 정책', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${evidence}/360-policy-disclosure.png` });
  await editor.getByRole('combobox', { name: 'OpenRouter 보관 정책', exact: true }).selectOption('standard');
  await expect(editor.getByRole('button', { name: '키 저장', exact: true })).toBeDisabled();
  await editor.getByRole('button', { name: '취소', exact: true }).click(); expect(calls).toHaveLength(1);
  await recovery.getByRole('button', { name: '보관 정책 검토', exact: true }).click();
  editor = page.getByRole('dialog', { name: 'API 키 수정', exact: true });
  await expect(editor.getByRole('combobox', { name: 'OpenRouter 보관 정책', exact: true })).toHaveValue('zdr');
  await editor.getByRole('combobox', { name: 'OpenRouter 보관 정책', exact: true }).selectOption('standard');
  await editor.getByRole('checkbox', { name: '선택한 OpenRouter 전송·보관 정책을 확인했어요', exact: true }).check();
  await editor.getByRole('button', { name: '키 저장', exact: true }).click(); await expect(editor).toHaveCount(0); expect(calls).toHaveLength(1);
  await expect(recovery).toHaveCount(0);
  await page.getByRole('button', { name: '최근 요청 다시 시도', exact: true }).click();
  const retry = page.getByRole('dialog', { name: '선택 청크 다시 전사', exact: true });
  await expect(retry).toContainText('모델 또는 설정이 달라 새 요청 묶음');
  await expect(retry.getByRole('button', { name: '전사 실행', exact: true })).toBeDisabled();
  await retry.getByRole('checkbox').check();
  await retry.getByRole('button', { name: '전사 실행', exact: true }).click();
  await expect(page.locator('.saved-count')).toHaveText('전사 결과 1 / 1');
  expect(calls).toHaveLength(2); expect(calls[1].provider).toMatchObject({ data_collection: 'deny', zdr: false });
  expect(external).toEqual([]); expect(errors).toEqual([]);
});
