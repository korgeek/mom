import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { createVault, toneWav, unlock } from './helpers';

test('uploaded file identity and compact prepared bytes remain clear after reload and preview selection', async ({ page }) => {
  const evidence = 'docs/superpowers/evidence/2026-10-17-upload-summary';
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('https://**/*', route => route.request().url() === 'https://openrouter.ai/api/v1/models'
    ? route.fulfill({ contentType: 'application/json', body: '{"data":[]}' }) : route.abort());
  await createVault(page);
  await page.getByRole('main').getByRole('button', { name: '+ 새 음성 메모', exact: true }).click();
  await page.getByRole('tab', { name: '파일 업로드', exact: true }).click();
  const fixture = { name: 'SYNTHETIC_UPLOAD_SUMMARY.wav', mimeType: 'audio/wav', buffer: toneWav() };
  await page.getByLabel('음성 파일 선택', { exact: true }).setInputFiles(fixture);
  const upload = page.getByRole('tabpanel', { name: '파일 업로드', exact: true });
  const preparation = page.getByRole('region', { name: '전사 준비', exact: true });
  await expect(upload.getByText(fixture.name, { exact: true })).toBeVisible();
  await expect(upload.getByText('31.3 KB', { exact: true })).toBeVisible();
  await expect(upload.getByRole('button', { name: '교체', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: '원본 다시 선택', exact: true })).toHaveCount(0);
  await expect(preparation.getByText(/원본은 암호화 저장돼 있어/)).toHaveCount(0);
  await expect(preparation.getByLabel('원본 음성 미리듣기', { exact: true })).toBeVisible();
  await expect(preparation.getByRole('button', { name: '미리듣기용 파일 선택', exact: true })).toHaveCount(0);
  const checkActionPosition = async () => {
    const replace = (await upload.getByRole('button', { name: '교체', exact: true }).boundingBox())!;
    await page.getByRole('tab', { name: '마이크 녹음', exact: true }).click();
    const microphone = page.getByRole('tabpanel', { name: '마이크 녹음', exact: true });
    const create = (await microphone.getByRole('button', { name: '새 음성 메모 만들기', exact: true }).boundingBox())!;
    expect(Math.abs(create.x + create.width - replace.x - replace.width)).toBeLessThan(1);
    await page.screenshot({ path: `${evidence}/${page.viewportSize()!.width}-ko-microphone-action.png`, fullPage: true });
    await page.getByRole('tab', { name: '파일 업로드', exact: true }).click();
  };
  mkdirSync(evidence, { recursive: true });
  await checkActionPosition();
  await preparation.getByRole('button', { name: '전사 준비', exact: true }).click();
  const status = preparation.getByRole('region', { name: '로컬 음성 준비', exact: true });
  await expect(status.getByRole('status')).toHaveText('로컬 음성 준비 완료');
  const count = status.getByText('암호화 저장된 음성 청크: 1 / 계획 1', { exact: true });
  await expect(count).toBeVisible();
  await expect(status.getByText(/^청크 용량: \d/)).toBeVisible();
  await expect(status.locator('details')).toHaveCount(0);
  expect(await count.evaluate(element => Number.parseFloat(getComputedStyle(element).fontSize))).toBeLessThanOrEqual(12);
  mkdirSync(evidence, { recursive: true });
  await page.screenshot({ path: `${evidence}/1440-ko-prepared.png`, fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  await checkActionPosition();
  await preparation.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true);
  expect((await upload.getByRole('button', { name: '교체', exact: true }).boundingBox())!.height).toBeLessThanOrEqual(44);
  await page.screenshot({ path: `${evidence}/360-ko-prepared.png`, fullPage: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.reload(); await unlock(page);
  await page.getByRole('button', { name: /^열기 / }).first().click();
  await expect(preparation.getByText(fixture.name, { exact: true })).toBeVisible();
  await expect(preparation.getByText(/^청크 용량: \d/)).toBeVisible();
  const reconnect = preparation.getByRole('button', { name: '미리듣기용 파일 선택', exact: true });
  await expect(reconnect).toBeEnabled();
  await page.screenshot({ path: `${evidence}/1440-ko-preview-needed.png`, fullPage: true });
  const chooser = page.waitForEvent('filechooser'); await reconnect.click(); await (await chooser).setFiles(fixture);
  await expect(preparation.getByLabel('원본 음성 미리듣기', { exact: true })).toBeVisible();
  await expect(reconnect).toHaveCount(0);
  await expect(preparation.getByRole('button', { name: '전사하기 →', exact: true })).toBeEnabled();
  await upload.getByRole('button', { name: '교체', exact: true }).click();
  await expect(upload.getByRole('button', { name: '파일 선택', exact: true })).toBeVisible();
  await expect(upload.getByText(fixture.name, { exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});
