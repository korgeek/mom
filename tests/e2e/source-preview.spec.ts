import { expect, test } from '@playwright/test';
import { clickAppAction, createVault, passphrase, toneWav } from './helpers';

test('saved source waveform offers real playback and seek after reload and lock/unlock without reselecting', async ({ page, baseURL }) => {
  const errors: string[] = [], external: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('https://**/*', route => { if (new URL(route.request().url()).origin === new URL(baseURL!).origin) return route.continue(); external.push(route.request().url()); return route.abort(); });
  await createVault(page);
  await page.getByRole('main').getByRole('button', { name: /새 음성 메모/ }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'SYNTHETIC_PREVIEW_RELOAD.wav', mimeType: 'audio/wav', buffer: toneWav(10) });
  const waveform = page.locator('.source-waveform svg path'), slider = page.getByRole('slider', { name: '원본 음성 재생 위치' }), audio = page.getByLabel('원본 음성 미리듣기', { exact: true });
  await expect(waveform).toBeVisible(); await expect(slider).toBeEnabled();
  expect((await waveform.getAttribute('d'))?.length).toBeGreaterThan(1000);
  await page.getByRole('button', { name: '원본 음성 재생', exact: true }).click();
  await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(.2);
  await page.getByRole('button', { name: '원본 음성 일시정지', exact: true }).click();
  await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).paused)).toBe(true);
  await slider.focus(); await page.keyboard.press('Home'); await page.keyboard.press('ArrowRight');
  await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).currentTime)).toBeCloseTo(.1, 1);
  const box = await slider.boundingBox(); expect(box).not.toBeNull();
  await page.mouse.click(box!.x + box!.width / 2, box!.y + box!.height / 2);
  await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(4);
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2); await page.mouse.down();
  await page.mouse.move(box!.x + box!.width * .75, box!.y + box!.height / 2, { steps: 6 }); await page.mouse.up();
  await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(7);
  await page.screenshot({ path: '/private/tmp/mom-audio-preview-1440.png', fullPage: true });
  await page.reload(); await page.getByLabel('암호', { exact: true }).fill(passphrase); await page.getByRole('button', { name: /^(화면 )?잠금 해제$/ }).click();
  await expect(page.getByRole('main')).toBeVisible();
  await page.locator('.sidebar').getByRole('button', { name: '새 음성 메모', exact: true }).click();
  await expect(waveform).toBeVisible(); await expect(slider).toBeEnabled();
  await expect(page.getByRole('button', { name: '미리듣기용 파일 선택', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '원본 음성 재생', exact: true }).click();
  await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).paused)).toBe(false);
  await clickAppAction(page, '화면 잠금'); await expect(page.getByRole('heading', { name: /^(화면이 잠겼어요|암호로 잠금 해제)$/ })).toBeVisible();
  await expect(page.locator('audio')).toHaveCount(0); await expect(waveform).toHaveCount(0);
  await page.getByLabel('암호', { exact: true }).fill(passphrase); await page.getByRole('button', { name: /^(화면 )?잠금 해제$/ }).click();
  await expect(waveform).toBeVisible(); await expect(slider).toBeEnabled();
  await page.getByRole('button', { name: '원본 음성 재생', exact: true }).click(); await expect.poll(() => audio.evaluate(element => (element as HTMLAudioElement).currentTime)).toBeGreaterThan(.2);
  await page.getByRole('button', { name: '원본 음성 일시정지', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 }); await slider.scrollIntoViewIfNeeded();
  await expect(waveform).toBeVisible(); const mobileBox = await slider.boundingBox();
  expect(mobileBox!.x).toBeGreaterThanOrEqual(0); expect(mobileBox!.x + mobileBox!.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: '/private/tmp/mom-audio-preview-390.png', fullPage: true });
  expect(errors).toEqual([]); expect(external).toEqual([]);
});
